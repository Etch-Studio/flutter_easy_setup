/// Starter templates for the promo site (V2_PLAN §5 store assets).
///
/// Deliberately plain and easy to rewrite: one small stylesheet driven by
/// CSS custom properties, three semantic pages. The AI skill (or the user)
/// restyles them; easy_setup never overwrites a page it did not just
/// create.
abstract final class SiteTemplates {
  /// Escapes a value for an HTML text node or a double-quoted attribute.
  /// Everything interpolated into the templates comes from user YAML, so
  /// it is escaped without exception.
  static String esc(String value) => value
      .replaceAll('&', '&amp;')
      .replaceAll('<', '&lt;')
      .replaceAll('>', '&gt;')
      .replaceAll('"', '&quot;')
      .replaceAll("'", '&#39;');

  /// Returns [url] when it is a safe http(s)/mailto link, else null —
  /// keeps `javascript:` and friends out of generated href attributes.
  static String? safeUrl(String? url) {
    if (url == null) return null;
    final trimmed = url.trim();
    final lower = trimmed.toLowerCase();
    if (lower.startsWith('http://') ||
        lower.startsWith('https://') ||
        lower.startsWith('mailto:') ||
        // Relative links inside the site.
        (!lower.contains(':') && !lower.startsWith('//'))) {
      return esc(trimmed);
    }
    return null;
  }

