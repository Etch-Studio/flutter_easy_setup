  /// GitHub Actions workflow publishing [siteDir] to Pages.
  static String pagesWorkflow(String siteDir) => '''
# Generated by easy_setup. Publishes the promo site to GitHub Pages.
# Enable once at: repo Settings > Pages > Source: GitHub Actions
name: Publish site

on:
  push:
    branches: [main]
    paths: ['$siteDir/**', '.github/workflows/pages.yml']
  workflow_dispatch:

permissions:
  contents: read
  pages: write
  id-token: write

concurrency:
  group: pages
  cancel-in-progress: true

jobs:
  deploy:
    runs-on: ubuntu-latest
    environment:
      name: github-pages
      url: \${{ steps.deployment.outputs.page_url }}
    steps:
      - uses: actions/checkout@v4
      - uses: actions/configure-pages@v5
      - uses: actions/upload-pages-artifact@v3
        with:
          path: '$siteDir'
      - id: deployment
        uses: actions/deploy-pages@v4
''';
