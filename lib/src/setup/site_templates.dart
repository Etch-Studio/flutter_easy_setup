  static String index({
    required String appName,
    required String tagline,
    required String description,
    required List<String> features,
    required String contactEmail,
    required String locale,
    String? appStoreUrl,
    String? playStoreUrl,
  }) {
    final featureItems = features
        .map((feature) =>
            '      <div class="feature"><span class="dot">◆</span>'
            '<p>${esc(feature)}</p></div>')
        .join('\n');
    final appStore = safeUrl(appStoreUrl);
    final playStore = safeUrl(playStoreUrl);
    final stores = [
      if (appStore != null)
        '      <a class="store-cta" href="$appStore">App Store</a>',
      if (playStore != null)
        '      <a class="store-cta" href="$playStore">Google Play</a>',
    ].join('\n');
    return '''
<!doctype html>
<html lang="${esc(locale)}">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>${esc(appName)}</title>
<meta name="description" content="${esc(tagline)}">
<link rel="icon" href="icon.png">
<link rel="stylesheet" href="style.css">
</head>
<body>
<div class="wrap">
${_header(appName, current: 'index')}
