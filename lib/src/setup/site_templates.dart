  static String _header(String appName, {required String current}) {
    final links = [
      if (current != 'index') '      <a href="index.html">Home</a>',
      if (current != 'support') '      <a href="support.html">Support</a>',
      if (current != 'privacy') '      <a href="privacy.html">Privacy</a>',
    ].join('\n');
    return '''
  <header class="site-header">
    <img src="icon.png" alt="${esc(appName)}">
    <span class="name">${esc(appName)}</span>
    <nav>
$links
    </nav>
  </header>
''';
  }

